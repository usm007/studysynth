"""Emit the offline service worker for the CTET Mock PWA.

The worker precaches the whole library: the app shell, the catalogue, the
icons and every mock. Once the install finishes the phone can open any paper
with the network off.
"""
from __future__ import annotations

import hashlib

CACHE_PREFIX = "ctet-mock-"

# The static shell, relative to the service worker. Files that do not exist
# yet are skipped by the build and reported.
SHELL_FILES = [
    "index.html",
    "app.css",
    "app.js",
    "player.html",
    "player.js",
    "manifest.webmanifest",
    "icons/icon-192.png",
    "icons/icon-512.png",
    "icons/icon-maskable-512.png",
    "icons/apple-touch-icon.png",
    "icons/favicon.png",
]

SERVICE_WORKER_TEMPLATE = """/* CTET Mock offline worker - generated by ctet-mock/build.py.
   Every asset below is precached so the library opens with no network. */
const VERSION = "{version}";
const CACHE_NAME = "{cache_name}";
const PRECACHE = [
{precache}
];

self.addEventListener("install", (event) => {{
  event.waitUntil((async () => {{
    const cache = await caches.open(CACHE_NAME);
    // One unreachable file must not cancel the whole offline library.
    await Promise.allSettled(
      PRECACHE.map((url) => cache.add(new Request(url, {{ cache: "reload" }})))
    );
    await self.skipWaiting();
  }})());
}});

self.addEventListener("activate", (event) => {{
  event.waitUntil((async () => {{
    const names = await caches.keys();
    await Promise.all(
      names.filter((name) => name !== CACHE_NAME).map((name) => caches.delete(name))
    );
    await self.clients.claim();
  }})());
}});

self.addEventListener("fetch", (event) => {{
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(respond(request, url));
}});

self.addEventListener("message", (event) => {{
  const data = event.data || {{}};
  if (data.type === "SKIP_WAITING") self.skipWaiting();
}});

async function respond(request, url) {{
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request, {{ ignoreSearch: true }});
  if (cached) return cached;
  try {{
    const response = await fetch(request);
    if (response && response.status === 200 && response.type === "basic") {{
      cache.put(request, response.clone());
    }}
    return response;
  }} catch (error) {{
    if (request.mode === "navigate") {{
      const shell = await cache.match("index.html");
      if (shell) return shell;
    }}
    throw error;
  }}
}}
"""


def compute_version(entries: list[tuple[str, bytes]]) -> str:
    """A short content hash over named byte blobs."""
    digest = hashlib.sha256()
    for name, data in sorted(entries, key=lambda item: item[0]):
        digest.update(name.encode("utf-8"))
        digest.update(b"\x00")
        digest.update(hashlib.sha256(data).hexdigest().encode("ascii"))
        digest.update(b"\x00")
    return digest.hexdigest()[:12]


def cache_name(version: str) -> str:
    return CACHE_PREFIX + version


def render_service_worker(version: str, precache: list[str]) -> str:
    """Render the worker source for a given version and asset list."""
    lines = "\n".join(f'  "{url}",' for url in precache)
    return SERVICE_WORKER_TEMPLATE.format(
        version=version,
        cache_name=cache_name(version),
        precache=lines,
    )
